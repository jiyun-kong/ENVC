#!/usr/bin/env python3
"""
Run DVS-Voltmeter on interpolated frames and save one event file per native-frame
interval (step 3 of generate_events.sh).

It reads high-fps frames generated by Super-SloMo, aggregates every `sf`
high-fps event intervals into one source-frame interval, and writes:

  <output_root>/{group}/{video_id}/images/000000.png ...  (source frames; already extracted)
  <output_root>/{group}/{video_id}/events/000000.npz ...

The high-fps interpolation folder can be deleted after each clip.
"""
import argparse
import json
import os
import shutil
from pathlib import Path

import cv2
import numpy as np
from tqdm import tqdm

import sys

sys.path.insert(0, str(Path(__file__).resolve().parent / "third_party" / "dvs_voltmeter"))
from src.simulator import EventSim  # noqa: E402


DEFAULT_MODEL_PARAMS = {
    "DVS346": [0.00018 * 29250, 20, 0.0001, 1e-7, 5e-9, 0.00001],
    "DVS240": [0.000094 * 47065, 23, 0.0002, 1e-7, 5e-8, 0.00001],
}


class _Node:
    pass


def parse_args():
    p = argparse.ArgumentParser(description="Simulate DVS events for interpolated clips.")
    p.add_argument(
        "--input_root",
        type=Path,
        required=True,
    )
    p.add_argument(
        "--output_root",
        type=Path,
        required=True,
    )
    p.add_argument("--camera_type", type=str, default="DVS346")
    p.add_argument("--model_para", type=float, nargs="+", default=None)
    p.add_argument(
        "--manifest",
        type=Path,
        default=None,
        help="Optional JSONL manifest with rel_path rows. start_index/limit apply to manifest rows.",
    )
    p.add_argument("--start_index", type=int, default=0)
    p.add_argument("--limit", type=int, default=0)
    p.add_argument("--skip_done", action="store_true")
    p.add_argument("--overwrite", action="store_true")
    p.add_argument("--delete_interp", action="store_true")
    p.add_argument("--dry_run", action="store_true")
    p.add_argument(
        "--log_every",
        type=int,
        default=100,
        help="Log DVS progress every N source-frame event files.",
    )
    return p.parse_args()


def integrate_cfg(args):
    cfg = _Node()
    cfg.SENSOR = _Node()
    cfg.DIR = _Node()
    cfg.SENSOR.CAMERA_TYPE = args.camera_type
    if args.model_para is not None:
        cfg.SENSOR.K = args.model_para
    else:
        cfg.SENSOR.K = DEFAULT_MODEL_PARAMS.get(args.camera_type)
    if cfg.SENSOR.K is None or len(cfg.SENSOR.K) != 6:
        raise ValueError("No model parameters given for sensor type {}".format(cfg.SENSOR.CAMERA_TYPE))
    cfg.DIR.IN_PATH = str(args.input_root)
    cfg.DIR.OUT_PATH = str(args.output_root)
    return cfg


def read_manifest(path):
    rows = []
    with path.open("r", encoding="utf-8") as f:
        for line_no, line in enumerate(f, start=1):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            row = json.loads(line)
            if "rel_path" not in row:
                raise ValueError("{}:{} missing rel_path".format(path, line_no))
            rows.append(row)
    return rows


def collect_manifest_clips(input_root, manifest, start_index, limit):
    rows = read_manifest(manifest)
    if start_index > 0:
        rows = rows[start_index:]
    if limit and limit > 0:
        rows = rows[:limit]

    clips = []
    for row in rows:
        clip = input_root / row["rel_path"]
        if not (clip / "images" / "info.txt").is_file() or not (clip / "source_meta.json").is_file():
            raise FileNotFoundError("manifest clip is not interpolated yet: {}".format(clip))
        clips.append(clip)
    return clips


def collect_clips(input_root, start_index, limit):
    clips = []
    for first in sorted(input_root.iterdir()):
        if not first.is_dir():
            continue
        for second in sorted(first.iterdir()):
            if (second / "images" / "info.txt").is_file() and (second / "source_meta.json").is_file():
                clips.append(second)
    if start_index > 0:
        clips = clips[start_index:]
    if limit and limit > 0:
        clips = clips[:limit]
    return clips


def read_info(info_path):
    rows = []
    base = info_path.parent
    with info_path.open("r", encoding="utf-8") as f:
        for line in f:
            parts = line.strip().split()
            if len(parts) < 2:
                continue
            raw_path = Path(parts[0])
            img_path = raw_path if raw_path.is_absolute() else base / raw_path
            rows.append((img_path, int(parts[1])))
    return rows


def final_done(out_clip, expected_source_frames):
    image_dir = out_clip / "images"
    event_dir = out_clip / "events"
    if expected_source_frames < 2:
        return False
    if not image_dir.is_dir() or not event_dir.is_dir():
        return False
    n_img = len(list(image_dir.glob("*.png")))
    return n_img >= expected_source_frames and existing_event_prefix(event_dir) >= expected_source_frames - 1


def existing_event_prefix(event_dir):
    i = 0
    while (event_dir / "{:06d}.npz".format(i)).is_file():
        i += 1
    return i


def remove_events_from(event_dir, start_index):
    removed = 0
    if not event_dir.is_dir():
        return removed
    for path in event_dir.glob("*.npz"):
        try:
            idx = int(path.stem)
        except ValueError:
            continue
        if idx >= start_index:
            path.unlink()
            removed += 1
    return removed


def clear_final(out_clip):
    for sub in ("events",):
        path = out_clip / sub
        if path.is_dir():
            shutil.rmtree(path)


def empty_event_arrays():
    return (
        np.array([], dtype=np.int32),
        np.array([], dtype=np.int32),
        np.array([], dtype=np.float64),
        np.array([], dtype=np.uint8),
    )


def merge_event_arrays(events):
    chunks = [event for event in events if event is not None and event.shape[0] > 0]
    if not chunks:
        return empty_event_arrays()
    merged = np.concatenate(chunks, axis=0)
    order = np.argsort(merged[:, 0], kind="stable")
    merged = merged[order]
    return (
        merged[:, 1].astype(np.int32),
        merged[:, 2].astype(np.int32),
        merged[:, 0].astype(np.float64),
        merged[:, 3].astype(np.uint8),
    )


def save_npz(path, events):
    x, y, t, p = merge_event_arrays(events)
    np.savez_compressed(path, x=x, y=y, timestamp=t, polarity=p)


def ensure_source_images(source_clip, out_clip):
    src_images = source_clip / "images"
    dst_images = out_clip / "images"
    if src_images.resolve() == dst_images.resolve():
        return
    dst_images.mkdir(parents=True, exist_ok=True)
    for src in sorted(src_images.glob("*.png")):
        dst = dst_images / src.name
        if not dst.exists():
            shutil.copy2(src, dst)


def process_clip(clip, input_root, output_root, sim_cfg, args):
    rel = clip.relative_to(input_root)
    out_clip = output_root / rel
    info_path = clip / "images" / "info.txt"
    with (clip / "source_meta.json").open("r", encoding="utf-8") as f:
        meta = json.load(f)

    sf = int(meta["sf"])
    source_frames = int(meta["source_frames"])
    expected_interp = (source_frames - 1) * sf + 1
    expected_events = source_frames - 1

    if args.skip_done and final_done(out_clip, source_frames):
        return "skip_done", rel, source_frames, source_frames - 1

    if args.overwrite:
        clear_final(out_clip)

    out_events = out_clip / "events"
    out_events.mkdir(parents=True, exist_ok=True)
    ensure_source_images(out_clip, out_clip)

    resume_prefix = 0 if args.overwrite else existing_event_prefix(out_events)
    if resume_prefix >= expected_events:
        return "skip_done", rel, source_frames, expected_events
    removed = remove_events_from(out_events, resume_prefix)
    if resume_prefix > 0 or removed > 0:
        print(
            "[resume] {}: existing event prefix={}/{}; removed_tail={}. "
            "Replaying prior high-fps frames to restore simulator state.".format(
                rel, resume_prefix, expected_events, removed
            ),
            flush=True,
        )

    rows = read_info(info_path)
    if len(rows) < expected_interp:
        raise ValueError("{} info.txt has {} frames, expected {}".format(rel, len(rows), expected_interp))
    if len(rows) > expected_interp:
        rows = rows[:expected_interp]

    sim = EventSim(cfg=sim_cfg, output_folder=str(output_root), video_name=str(rel))
    pending = []
    saved = resume_prefix
    t0 = None

    for i, (image_path, timestamp_us) in enumerate(rows):
        image = cv2.imread(str(image_path), cv2.IMREAD_GRAYSCALE)
        if image is None:
            raise FileNotFoundError("failed to read {}".format(image_path))
        event = sim.generate_events(image, timestamp_us)

        if i == 0:
            continue
        pending.append(event)
        if i % sf == 0:
            event_index = i // sf - 1
            if event_index >= resume_prefix:
                if t0 is None:
                    import time

                    t0 = time.time()
                save_npz(out_events / "{:06d}.npz".format(event_index), pending)
                saved += 1
                if args.log_every > 0 and (saved % args.log_every == 0 or saved == expected_events):
                    import time

                    elapsed = time.time() - t0
                    new_done = saved - resume_prefix
                    rate = new_done / elapsed if elapsed > 0 else 0.0
                    remaining = expected_events - saved
                    eta = remaining / rate if rate > 0 else float("inf")
                    print(
                        "[dvs] {} events {}/{} ({:.3f} event-file/s, ETA {:.1f}h)".format(
                            rel, saved, expected_events, rate, eta / 3600.0
                        ),
                        flush=True,
                    )
            pending = []

    if pending:
        raise RuntimeError("{} ended with {} unmerged high-fps intervals".format(rel, len(pending)))

    sim.reset()
    final_meta = dict(meta)
    final_meta.update(
        {
            "final_event_pattern": "events/{:06d}.npz",
            "final_image_pattern": "images/{:06d}.png",
            "final_events": saved,
        }
    )
    with (out_clip / "source_meta.json").open("w", encoding="utf-8") as f:
        json.dump(final_meta, f, indent=2)
        f.write("\n")

    if args.delete_interp:
        shutil.rmtree(clip)
        parent = clip.parent
        try:
            parent.rmdir()
        except OSError:
            pass

    return "ok", rel, source_frames, saved


def main():
    args = parse_args()
    input_root = args.input_root.resolve()
    output_root = args.output_root.resolve()
    if not input_root.is_dir():
        raise FileNotFoundError("input_root not found: {}".format(input_root))

    sim_cfg = integrate_cfg(args)
    if args.manifest is not None:
        clips = collect_manifest_clips(input_root, args.manifest.resolve(), args.start_index, args.limit)
    else:
        clips = collect_clips(input_root, args.start_index, args.limit)
    print("[scan] clips={} input_root={}".format(len(clips), input_root), flush=True)
    print("[out]  output_root={}".format(output_root), flush=True)

    if args.dry_run:
        for clip in clips[:50]:
            with (clip / "source_meta.json").open("r", encoding="utf-8") as f:
                meta = json.load(f)
            rel = clip.relative_to(input_root)
            print(
                "{} source_frames={} sf={} interp_frames={}".format(
                    rel,
                    meta.get("source_frames"),
                    meta.get("sf"),
                    meta.get("interpolated_frames"),
                ),
                flush=True,
            )
        if len(clips) > 50:
            print("... {} more".format(len(clips) - 50), flush=True)
        return

    counts = {}
    for clip in tqdm(clips, desc="dvs"):
        status, rel, frames, events = process_clip(clip, input_root, output_root, sim_cfg, args)
        counts[status] = counts.get(status, 0) + 1
        tqdm.write("[{}] {} source_frames={} events={}".format(status, rel, frames, events))
    print("[done] {}".format(counts), flush=True)


if __name__ == "__main__":
    main()
